// Plain module — deliberately NO 'use server' directive. Every export from a
// 'use server' file is a client-callable POST endpoint; `generateEvents`
// takes a caller-supplied `userId` and `generateEventsForSeries` trusts a
// caller-supplied series row (its UPDATE has no ownership predicate, and
// inserts stamp `userId` straight from the row) — either export reached as
// an endpoint is arbitrary cross-user event injection. Import-only surface:
// only `src/server/actions/event-generation.ts`'s zero-arg, auth-derived
// `safeGenerateEvents()` and the series CRUD actions (`src/server/actions/series.ts`,
// A4) may call in.
import { db } from '@/db'
import { events, eventSeries } from '@/db/schema'
import { and, eq, gte, lt, or } from 'drizzle-orm'
import { logger } from '@/lib/logger'
import {
  generateSeriesSeeds,
  nextGeneratedThrough,
  resolveGenerationWindow,
} from '@/lib/series-generation'

type SeriesRow = (typeof eventSeries)['$inferSelect']

/**
 * Generates and persists a single series' due events for the sliding 8-week
 * window anchored at `now`, then advances its high-water mark
 * (`generatedThrough`) via `nextGeneratedThrough` — even when zero seeds are
 * due, so a fully-elapsed or between-occurrence series' mark still tracks
 * forward (or pins at `until`) and a repeat sweep at the same instant is
 * idempotent. Shared by the series CRUD actions (immediate, single series —
 * `src/server/actions/series.ts`, A4) and the bulk sweep below.
 *
 * Dedupe guard: an existing PENDING event within the window counts as
 * "already generated" when it carries this series' `seriesId`, OR — when the
 * series still has an `activityId` — when it carries that `activityId`. The
 * `activityId` arm is the migration-0021-transition belt: rows generated by
 * the retired activity-schedule sweep carry no `seriesId`, so without it the
 * first post-cutover sweep would duplicate every activity-derived series'
 * upcoming occurrences.
 */
export async function generateEventsForSeries(series: SeriesRow, now: Date): Promise<number> {
  const window = resolveGenerationWindow(now)

  const dedupeMatch = series.activityId
    ? or(eq(events.seriesId, series.id), eq(events.activityId, series.activityId))
    : eq(events.seriesId, series.id)

  const existingRows = await db
    .select({ startAt: events.startAt })
    .from(events)
    .where(
      and(
        eq(events.userId, series.userId),
        eq(events.status, 'pending'),
        gte(events.startAt, window.from),
        lt(events.startAt, window.to),
        dedupeMatch,
      ),
    )
  const existingStartAtMs = new Set<number>()
  for (const row of existingRows) {
    if (row.startAt !== null) existingStartAtMs.add(row.startAt.getTime())
  }

  const seeds = generateSeriesSeeds({ series, window, existingStartAtMs })

  if (seeds.length > 0) {
    await db.insert(events).values(
      seeds.map((seed) => ({
        userId: series.userId,
        activityId: series.activityId,
        seriesId: series.id,
        title: seed.title,
        description: seed.description,
        location: seed.location,
        color: seed.color,
        visibility: seed.visibility,
        startAt: seed.startAt,
        endAt: seed.endAt,
        status: 'pending' as const,
      })),
    )
  }

  await db
    .update(eventSeries)
    .set({ generatedThrough: nextGeneratedThrough(window, series.until), updatedAt: new Date() })
    .where(eq(eventSeries.id, series.id))

  return seeds.length
}

/**
 * Bulk sliding-window sweep: regenerates every one of `userId`'s series.
 * `userId` is passed explicitly (no auth here) — this module is import-only,
 * never a server action; `safeGenerateEvents`
 * (`src/server/actions/event-generation.ts`) resolves the session and is the
 * only client-reachable caller.
 */
export async function generateEvents(userId: string): Promise<number> {
  const now = new Date()
  const rows = await db.select().from(eventSeries).where(eq(eventSeries.userId, userId))

  let total = 0
  for (const series of rows) {
    total += await generateEventsForSeries(series, now)
  }

  logger.info({ userId, series: rows.length, generated: total }, 'Events generation swept')
  return total
}
